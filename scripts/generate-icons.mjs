import { readFile, writeFile } from 'node:fs/promises';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

process.chdir(fileURLToPath(new URL('..', import.meta.url)));
// The sidebar mask, application icon and monochrome tray share one glyph.
const radar = await readFile('src/assets/radar.svg', 'utf8');
const drawing = radar.match(/<svg\b[^>]*>([\s\S]*?)<\/svg>/);
if (!drawing) throw new Error('radar.svg must contain an SVG drawing');
const shape = drawing[1].trim();
const stroke = 'fill="none" stroke-width="2" stroke-linecap="round" stroke-linejoin="round"';
const notice = '<!-- Generated by npm run icons from radar.svg. Lucide ISC: THIRD_PARTY_NOTICES.md. -->';
await writeFile('src/assets/icon.svg', `${notice}
<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="1024" viewBox="0 0 1024 1024">
  <defs>
    <linearGradient id="background" x1="0" y1="0" x2="0.8" y2="1">
      <stop stop-color="#348563"/><stop offset="1" stop-color="#19553b"/>
    </linearGradient>
    <filter id="shadow" x="-10%" y="-10%" width="120%" height="125%">
      <feDropShadow dx="0" dy="12" stdDeviation="12" flood-color="#173b26" flood-opacity="0.13"/>
    </filter>
  </defs>
  <rect x="64" y="64" width="896" height="896" rx="203" fill="url(#background)" filter="url(#shadow)"/>
  <svg x="246" y="246" width="532" height="532" viewBox="0 0 24 24" stroke="#f2fff7" ${stroke}>
    ${shape}
  </svg>
</svg>
`);
await writeFile('src/assets/tray.svg', `${notice}
<svg xmlns="http://www.w3.org/2000/svg" width="44" height="44" viewBox="0 0 24 24" stroke="#000" ${stroke}>
  ${shape}
</svg>
`);
for (const args of [
  ['icon', 'src/assets/icon.svg', '--output', 'src-tauri/icons'],
  ['icon', 'src/assets/tray.svg', '--output', 'src-tauri/icons/tray', '--png', '44'],
]) {
  const result = spawnSync('./node_modules/.bin/tauri', args, { stdio: 'inherit' });
  if (result.error) throw result.error;
  if (result.status !== 0) process.exit(result.status ?? 1);
}
